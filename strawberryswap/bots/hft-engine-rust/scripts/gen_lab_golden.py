"""Writes src/lab_golden.rs: the Python lab's own outputs for a grid of inputs, for the Rust engine's golden tests.

Usage (from this crate's directory, with the lab's requirements installed):

    python3 scripts/gen_lab_golden.py [--lab ../../hft-engine/python-sim]

The values come from as_sim/model.py itself (reservation_price, optimal_spread, quotes, fill_probability), not from a
re-implementation. Every float is written with repr(), the shortest decimal that round-trips, so the Rust literal is the
exact same f64. The lab takes σ and squares it; the engine takes σ², so the σ² written is np.square(σ), the very value
the lab used.
"""

from __future__ import annotations

import argparse
import math
import platform
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent.parent


def f(x: float) -> str:
    x = float(x)
    if not math.isfinite(x):
        raise ValueError(f"non-finite value {x!r}")
    return repr(x)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--lab", type=Path, default=HERE.parent.parent / "hft-engine" / "python-sim",
                    help="the Python lab's directory (strawberryswap/hft-engine/python-sim)")
    ap.add_argument("--out", type=Path, default=HERE / "src" / "lab_golden.rs")
    args = ap.parse_args()
    sys.path.insert(0, str(args.lab.resolve()))
    from as_sim import model  # noqa: E402  (the lab under test)

    rng = np.random.default_rng(20261110)
    cases: list[tuple[float, float, float, float, float, float, float]] = []  # mid, q, gamma, sigma, tau, kappa, tick

    def logu(lo: float, hi: float) -> float:
        return float(math.exp(rng.uniform(math.log(lo), math.log(hi))))

    # Random cases over wide ranges: far-from-mid reservation prices exercise the never-cross-the-mid guard.
    for _ in range(48):
        cases.append((
            logu(0.5, 5000.0),
            0.0 if rng.uniform() < 0.1 else float(rng.uniform(-2000.0, 2000.0)),
            logu(1e-6, 10.0),
            logu(1e-4, 1.0),
            float(rng.choice([0.0, 1.0, 60.0, 3600.0, 11670.0])),
            logu(1e-2, 1e4),
            float(rng.choice([0.0, 1e-6, 1e-4, 0.01])),
        ))
    # The engine's mock market (mid 2, σ = 0.0005/√s, γ 0.1, τ 60 s, κ 500, tick 0.0001) across inventories.
    for q in (-1000.0, -100.0, 0.0, 100.0, 1000.0):
        cases.append((2.0, q, 0.1, 0.0005, 60.0, 500.0, 1e-4))
    # The lab's synthetic calibration.json engine block (γ 0.016, σ² 3.96e-4/s, τ 11670 s, κ 13.8).
    sig = math.sqrt(0.00039623631218582077)
    for q in (-3.0, 0.0, 2.0):
        cases.append((100.0, q, 0.016, sig, 11670.0, 13.803083097931438, 0.01))
    # γ/κ = 1e-16: ln(1 + γ/κ) would round to 0 here; the spread must still be 2/κ.
    cases.append((2.0, 0.0, 1e-12, 0.0, 60.0, 1e4, 0.0))
    # γ/κ = 1000.
    cases.append((2.0, 5.0, 10.0, 0.01, 60.0, 1e-2, 0.0))
    # No horizon or no volatility: r equals the mid whatever the inventory.
    cases.append((3.5, 750.0, 0.2, 0.0, 60.0, 50.0, 1e-4))
    cases.append((3.5, -750.0, 0.2, 0.02, 0.0, 50.0, 1e-4))
    # Very large inventories: the near-side quote is held at the mid.
    cases.append((2.0, 1e6, 0.1, 0.0005, 60.0, 500.0, 1e-4))
    cases.append((2.0, -1e6, 0.1, 0.0005, 60.0, 500.0, 1e-4))

    rows = []
    for mid, q, gamma, sigma, tau, kappa, tick in cases:
        r, bid, ask = model.quotes(mid, q, gamma, sigma, tau, kappa, tick)
        spread = model.optimal_spread(gamma, sigma, tau, kappa)
        r_alone = model.reservation_price(mid, q, gamma, sigma, tau)
        assert float(r_alone) == float(r)
        sigma2 = float(np.square(sigma))
        rows.append([mid, q, gamma, sigma2, tau, kappa, tick, r, bid, ask, spread])

    fills = []
    for delta in (-0.01, 0.0, 1e-6, 0.002, 0.05, 1.0):
        for a in (0.04, 0.5):
            for kappa in (13.803083097931438, 500.0):
                for dt in (0.1, 60.0):
                    fills.append([delta, a, kappa, dt, model.fill_probability(delta, a, kappa, dt)])

    lines = [
        "//! Generated by scripts/gen_lab_golden.py from the Python lab's as_sim/model.py: do not edit by hand.",
        f"//! Python {platform.python_version()}, numpy {np.__version__}. Every literal is the shortest decimal that",
        "//! round-trips, so it is the lab's exact f64.",
        "",
        "/// mid, inventory, γ, σ², τ, κ, tick, then the lab's r, bid, ask (from `quotes`) and spread (`optimal_spread`).",
        "#[rustfmt::skip]",
        "pub(crate) const QUOTES: &[[f64; 11]] = &[",
    ]
    lines += ["    [" + ", ".join(f(x) for x in row) + "]," for row in rows]
    lines += [
        "];",
        "",
        "/// δ, A (per second), κ, dt (seconds), then the lab's `fill_probability`.",
        "#[rustfmt::skip]",
        "pub(crate) const FILL_PROBABILITY: &[[f64; 5]] = &[",
    ]
    lines += ["    [" + ", ".join(f(x) for x in row) + "]," for row in fills]
    lines += ["];", ""]
    args.out.write_text("\n".join(lines))
    print(f"wrote {args.out}: {len(rows)} quote cases, {len(fills)} fill-probability cases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
