// Writes src/planner_golden.rs: the C++ planner's own outputs (bots/inventory-cpp/include/strawberry/curve.hpp) for a
// grid of inputs, for the Rust port's golden tests.
//
//   g++ -std=c++20 -O2 -ffp-contract=off -I ../inventory-cpp/include scripts/gen_planner_golden.cpp -o gen
//   ./gen > src/planner_golden.rs
//
// -ffp-contract=off: no fused multiply-add, so every operation rounds once, as in Rust. Every double is printed in
// its shortest round-trip form (std::to_chars), so the Rust literal is the exact same f64.
#include <charconv>
#include <cstdio>
#include <cstring>
#include <random>
#include <vector>
#include "strawberry/curve.hpp"

namespace {

void num(double x) {
  char buf[64];
  const auto end = std::to_chars(buf, buf + sizeof buf - 1, x).ptr;
  *end = '\0';
  // A Rust f64 literal needs a '.' or an exponent.
  const bool plain = std::strpbrk(buf, ".en") == nullptr;
  std::printf("%s%s, ", buf, plain ? ".0" : "");
}

struct Case {
  sb::PoolState s;
  double P, bid, ask;
  sb::PlannerParams pp;
};

void row(const Case& c) {
  const sb::Plan p = sb::plan(c.s, c.P, c.bid, c.ask, c.pp);
  const sb::RuleCheck r = sb::chainRules(c.s, c.P, p.amount0Out, p.amount1Out, p.pay0, p.pay1, p.treasuryPay);
  std::printf("    [");
  for (double x : {c.s.r0, c.s.r1, c.s.v0, c.s.v1, c.P, c.bid, c.ask, c.pp.gasCostQuote, c.pp.minNet, c.pp.maxInv0, c.pp.maxInv1}) num(x);
  for (double x : {p.ok ? 1.0 : 0.0, p.sellsToken0 ? 1.0 : 0.0, p.amount0Out, p.amount1Out, p.pay0, p.pay1, p.treasuryPay, p.harvest,
                   p.edge, p.net, p.targetPrice})
    num(x);
  for (double x : {r.kOk ? 1.0 : 0.0, r.deviationOk ? 1.0 : 0.0, r.treasuryOk ? 1.0 : 0.0, r.cut}) num(x);
  std::printf("],\n");
}

}  // namespace

int main() {
  std::vector<Case> cases;
  // The C++ self-test's property-test distribution: random pools, an oracle within ±2 % of spot, A-S quotes around it.
  std::mt19937_64 g(20261111);
  std::uniform_real_distribution<double> u(0, 1);
  for (int i = 0; i < 300; ++i) {
    Case c{};
    c.s = {50 + u(g) * 5000, 1e5 + u(g) * 1e7, 10 + u(g) * 1000, 1e4 + u(g) * 1e6};
    c.P = c.s.spot() * (1 + (u(g) - 0.5) * 0.04);
    const double half = u(g) * 0.002 * c.P, skew = (u(g) - 0.5) * 0.002 * c.P;
    c.bid = c.P + skew - half;
    c.ask = c.P + skew + half;
    c.pp.gasCostQuote = u(g) * 2;
    c.pp.maxInv0 = u(g) * 200;
    c.pp.maxInv1 = u(g) * 4e5;
    c.pp.minNet = (i % 7 == 0) ? u(g) * 50 : 0;
    cases.push_back(c);
  }
  // Edge cases: the self-test's fixed pool, the oracle on the spot, a hair off it, no inventory, deep inventory,
  // quotes far on either side.
  const sb::PoolState fixed{1000, 2e6, 1000, 2e6};  // spot 2000
  auto add = [&](double P, double bid, double ask, double gas, double minNet, double inv0, double inv1) {
    Case c{};
    c.s = fixed;
    c.P = P;
    c.bid = bid;
    c.ask = ask;
    c.pp.gasCostQuote = gas;
    c.pp.minNet = minNet;
    c.pp.maxInv0 = inv0;
    c.pp.maxInv1 = inv1;
    cases.push_back(c);
  };
  add(1980, 1979, 1981, 1, 0, 1e9, 1e12);           // pool above the oracle: sell token0
  add(2020, 2019, 2021, 1, 0, 1e9, 1e12);           // pool below the oracle: buy token0
  add(2000, 1999, 2001, 0, 0, 1e9, 1e12);           // oracle on the spot: nothing to do
  add(2000 * (1 + 1e-10), 1999, 2001, 0, 0, 1e9, 1e12);
  add(1980, 1979, 1981, 0, 0, 0, 0);                // no inventory
  add(1980, 1979, 1981, 0, 0, 1e-3, 1e12);          // almost no token0
  add(2020, 2019, 2021, 0, 0, 1e9, 1e-3);           // almost no token1
  add(1985, 1900, 1950, 0, 0, 1e9, 1e12);           // very long book: ask under the oracle
  add(1985, 2050, 2100, 0, 0, 1e9, 1e12);           // very short book: bid over the oracle
  add(1990, 1989, 1991, 0, 1e9, 1e9, 1e12);         // min net out of reach
  add(1990, 1989, 1991, 1e9, 0, 1e9, 1e12);         // gas out of reach

  std::printf(
      "//! Generated by scripts/gen_planner_golden.cpp from bots/inventory-cpp/include/strawberry/curve.hpp: do not edit\n"
      "//! by hand. Every literal is the shortest form of the C++ planner's double, so it parses to the exact same f64.\n\n"
      "/// r0, r1, v0, v1, P, bid, ask, gasCostQuote, minNet, maxInv0, maxInv1 (extraction 8000 bps, margin 5 bps), then\n"
      "/// plan(): ok, sellsToken0, amount0Out, amount1Out, pay0, pay1, treasuryPay, harvest, edge, net, targetPrice, then\n"
      "/// chainRules() on those amounts: kOk, deviationOk, treasuryOk, cut.\n"
      "#[rustfmt::skip]\n"
      "pub(crate) const PLANS: &[[f64; 26]] = &[\n");
  for (const Case& c : cases) row(c);
  std::printf("];\n");
}
