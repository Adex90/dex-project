// Generates the Foundry fixtures: REAL Groth16 proofs + verifiers (dev key) + the Poseidon contract bytecode.
//   contracts/test/fixtures/PoseidonT3Code.sol        circomlibjs Poseidon(2) EVM bytecode
//   contracts/test/fixtures/*Groth16Verifier.dev.sol  snarkjs verifiers for the DEV keys (never deploy!)
//   contracts/test/fixtures/Fixtures.sol              proofs for: shield -> transferZK -> unshield, oracle attestation
// Everything is deterministic (fixed seeds) so regenerated fixtures diff cleanly.
import * as snarkjs from "snarkjs";
import { poseidonContract } from "circomlibjs";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { keccak256, toBytes, getAddress } from "viem";
import { init, Tree, makeNote, dummyNote, buildInput, extDataHash, stringify, FIELD } from "../test/lib.mjs";

const OUT = "../contracts/test/fixtures";
mkdirSync(OUT, { recursive: true });
const h = await init();
const det = (label) => BigInt(keccak256(toBytes(label))) % FIELD; // deterministic "randomness"
const hex32 = (x) => "0x" + BigInt(x).toString(16).padStart(64, "0");
const ALICE = getAddress("0x00000000000000000000000000000000000a11ce");
const RECIPIENT = getAddress("0x0000000000000000000000000000000000000b0b");
const ZERO_ADDR = "0x0000000000000000000000000000000000000000";
const UNIT = 10n ** 18n;

// ---------------------------------------------------------------- Poseidon bytecode
writeFileSync(`${OUT}/PoseidonT3Code.sol`, `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;
// GENERATED by circuits/scripts/gen-fixtures.mjs from circomlibjs poseidonContract.createCode(2)
// (Poseidon, BN254, t=3: identical to circom's Poseidon(2)). Deployed with CREATE in tests.
library PoseidonT3Code {
    bytes internal constant CODE = hex"${poseidonContract.createCode(2).slice(2)}";
}
`);

// ---------------------------------------------------------------- verifiers (rename, add DEV banner)
for (const [name, cls] of [["joinsplit", "JoinSplitGroth16Verifier"], ["zkdeco_oracle", "OracleGroth16Verifier"]]) {
  let src = readFileSync(`build/${name}/${name}.Verifier.sol`, "utf8").replace(/contract Groth16Verifier/, `contract ${cls}`);
  src = `// ⚠ DEV-ONLY VERIFICATION KEY — generated from a single-party local setup (scripts/setup-dev.mjs).\n// Anyone holding that setup's toxic waste can forge proofs. TEST FIXTURE: NEVER DEPLOY.\n` + src;
  writeFileSync(`${OUT}/${cls}.dev.sol`, src);
}

// ---------------------------------------------------------------- proving helpers
const JS_WASM = "build/joinsplit/joinsplit_js/joinsplit.wasm", JS_ZKEY = "build/joinsplit/joinsplit.zkey";
const vkJS = JSON.parse(readFileSync("build/joinsplit/joinsplit.vkey.json", "utf8"));

async function prove(input, wasm, zkey, vkey, expectedPublic) {
  const { proof, publicSignals } = await snarkjs.groth16.fullProve(stringify(input), wasm, zkey);
  if (!(await snarkjs.groth16.verify(vkey, publicSignals, proof))) throw new Error("local verification failed");
  if (publicSignals.length !== expectedPublic.length || publicSignals.some((s, i) => BigInt(s) !== BigInt(expectedPublic[i])))
    throw new Error(`public signal order mismatch:\n got ${publicSignals}\n exp ${expectedPublic}`);
  const cd = JSON.parse(`[${await snarkjs.groth16.exportSolidityCallData(proof, publicSignals)}]`);
  const [a, b, c] = cd;
  const words = [...a, ...b[0], ...b[1], ...c].map((x) => BigInt(x).toString(16).padStart(64, "0"));
  return "0x" + words.join(""); // == abi.encode(uint256[2], uint256[2][2], uint256[2])
}

// ---------------------------------------------------------------- JoinSplit: shield -> transferZK -> unshield
const tree = new Tree(h);
const alice = { priv: det("alice.priv") }, bob = { priv: det("bob.priv") };
const note = (label, owner, value) => makeNote(h, { value, privKey: owner.priv, blinding: det(label) });
// dummy notes need a deterministic key too
const dummy = (label) => makeNote(h, { value: 0n, privKey: det(label + ".k"), blinding: det(label + ".b") });
const enc = (n) => "0x" + n.toString(16).padStart(4, "0");

const fx = {};
async function step(name, { caller, ins, outs, publicIn = 0n, publicOut = 0n, encs }) {
  const ext = extDataHash(getAddress(caller), encs[0], encs[1]);
  const input = buildInput(h, tree, { ins, outs, publicIn, publicOut, ext });
  const pub = [input.root, ...input.nullifier, ...input.commitment, publicIn, publicOut, ext, 0n];
  const proof = await prove(input, JS_WASM, JS_ZKEY, vkJS, pub);
  fx[name] = { proof, root: input.root, n0: input.nullifier[0], n1: input.nullifier[1], c0: input.commitment[0], c1: input.commitment[1], enc0: encs[0], enc1: encs[1], publicIn, publicOut };
  outs.forEach((o) => tree.insert(o.commitment)); // the contract inserts commitments[0], then [1]
  console.log(`  proved ${name}`);
}

const A = note("A", alice, 100n * UNIT);
const D1 = dummy("D1");
await step("shield", { caller: ALICE, ins: [null, null], outs: [A, D1], publicIn: 100n * UNIT, encs: [enc(0x1111), enc(0x2222)] });
const B = note("B", bob, 60n * UNIT), C = note("C", alice, 40n * UNIT);
await step("transfer", { caller: ZERO_ADDR, ins: [{ note: A, index: 0 }, null], outs: [B, C], encs: [enc(0x3333), enc(0x4444)] });
await step("unshield", { caller: RECIPIENT, ins: [{ note: B, index: 2 }, null], outs: [dummy("D2"), dummy("D3")], publicOut: 60n * UNIT, encs: [enc(0x5555), enc(0x6666)] });

// ---------------------------------------------------------------- zk-DECO oracle attestation
const ORC_WASM = "build/zkdeco_oracle/zkdeco_oracle_js/zkdeco_oracle.wasm", ORC_ZKEY = "build/zkdeco_oracle/zkdeco_oracle.zkey";
const vkOrc = JSON.parse(readFileSync("build/zkdeco_oracle/zkdeco_oracle.vkey.json", "utf8"));
const BODY = '{"symbol":"XAUUSD","price":2345.678912,"ts":1767225600}';
const body = [...Buffer.from(BODY, "latin1")]; while (body.length < 96) body.push(0);
const pack = (arr) => arr.reduce((a, b, i) => a + (BigInt(b) << BigInt(8 * i)), 0n);
const sym = [...Buffer.from("XAUUSD", "latin1")], salt = det("oracle.salt");
const chunks = [0, 1, 2, 3].map((j) => pack(body.slice(j * 24, (j + 1) * 24)));
const providerId = det("StrawberrySwap.provider.example");
const oin = {
  providerId, queryCommitment: h(pack(sym), salt), price: 2345678912n * 10n ** 12n, observedAt: 1767225600n, bodyCommitment: h(...chunks),
  body, symbol: sym, salt, offSymKey: BODY.indexOf('"symbol":"'), offPriceKey: BODY.indexOf('"price":'), offTsKey: BODY.indexOf('"ts":'),
  intLen: 4, fracLen: 6,
};
const oproof = await prove(oin, ORC_WASM, ORC_ZKEY, vkOrc, [oin.providerId, oin.queryCommitment, oin.price, oin.observedAt, oin.bodyCommitment]);
console.log("  proved oracle attestation");

// ---------------------------------------------------------------- Fixtures.sol
const caseSol = (n, c) => `    function ${n}() internal pure returns (Case memory) {
        return Case({
            proof: hex"${c.proof.slice(2)}",
            root: ${hex32(c.root)},
            n0: ${hex32(c.n0)},
            n1: ${hex32(c.n1)},
            c0: ${hex32(c.c0)},
            c1: ${hex32(c.c1)},
            enc0: hex"${c.enc0.slice(2)}",
            enc1: hex"${c.enc1.slice(2)}",
            amount: ${c.publicIn || c.publicOut}
        });
    }
`;
writeFileSync(`${OUT}/Fixtures.sol`, `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;
// GENERATED by circuits/scripts/gen-fixtures.mjs — real Groth16 proofs against the DEV verification keys.

library Fixtures {
    address internal constant ALICE = ${ALICE};
    address internal constant RECIPIENT = ${RECIPIENT};

    struct Case {
        bytes proof; bytes32 root; bytes32 n0; bytes32 n1; bytes32 c0; bytes32 c1; bytes enc0; bytes enc1; uint256 amount;
    }

${caseSol("shield", fx.shield)}
${caseSol("transfer", fx.transfer)}
${caseSol("unshield", fx.unshield)}
    // ---- zk-DECO oracle attestation for body: ${BODY}
    bytes32 internal constant ORACLE_PROVIDER_ID = ${hex32(oin.providerId)};
    bytes32 internal constant ORACLE_QUERY_COMMITMENT = ${hex32(oin.queryCommitment)};
    uint256 internal constant ORACLE_PRICE = ${oin.price};
    uint64 internal constant ORACLE_OBSERVED_AT = ${oin.observedAt};
    bytes32 internal constant ORACLE_BODY_COMMITMENT = ${hex32(oin.bodyCommitment)};
    bytes internal constant ORACLE_SNARK_PROOF = hex"${oproof.slice(2)}";
}
`);
console.log("fixtures written to", OUT);
// snarkjs keeps its worker threads alive after proving; exit explicitly so scripted pipelines do not hang.
process.exit(0);
