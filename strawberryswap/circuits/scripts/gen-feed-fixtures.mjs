// Generates contracts/test/fixtures/FeedFixtures.sol: REAL Groth16 proofs of circuits/zkdeco_oracle (DEV key) for a
// short ETHUSD price series, 15 s apart, as the testnet relayer would push them to ZkPriceFeed.
//
//   node scripts/gen-feed-fixtures.mjs        (needs build/zkdeco_oracle from scripts/setup-dev.mjs)
//
// Each body is the circuit's canonical single object {"symbol":"ETHUSD","price":<I>.<F>,"ts":<10 digits>}. The prices
// use 1, 4, 6 and 10 fractional digits, so the fixtures cover the parser's whole range. Every proof is verified
// locally against the verification key before it is written. The notary's signature is not part of the fixture:
// the Foundry tests sign (providerId, bodyCommitment) with their own test notary key, as ZkDecoIntegration does.
import * as snarkjs from "snarkjs";
import { readFileSync, writeFileSync } from "node:fs";
import { keccak256, toBytes } from "viem";
import { init, stringify, FIELD } from "../test/lib.mjs";

const OUT = "../contracts/test/fixtures/FeedFixtures.sol";
const WASM = "build/zkdeco_oracle/zkdeco_oracle_js/zkdeco_oracle.wasm";
const ZKEY = "build/zkdeco_oracle/zkdeco_oracle.zkey";
const vkey = JSON.parse(readFileSync("build/zkdeco_oracle/zkdeco_oracle.vkey.json", "utf8"));

const h = await init();
const det = (label) => BigInt(keccak256(toBytes(label))) % FIELD; // deterministic, documented test values
const hex32 = (x) => "0x" + BigInt(x).toString(16).padStart(64, "0");
const pack = (arr) => arr.reduce((a, b, i) => a + (BigInt(b) << BigInt(8 * i)), 0n);

// The testnet's price endpoint as a registry key (in production: hash of the domain and its TLS key root).
const providerId = det("StrawberrySwap.testnet.price-endpoint");
const SYMBOL = "ETHUSD";
const symbol = [...Buffer.from(SYMBOL, "latin1")];
const salt = det("StrawberrySwap.testnet.ETHUSD.salt");
const queryCommitment = h(pack(symbol), salt);

const T0 = 1767225600n; // 2026-01-01T00:00:00Z
const SERIES = [
  { price: "3456.789012", ts: T0 },
  { price: "3457.1205", ts: T0 + 15n },
  { price: "3455.9", ts: T0 + 30n },
  { price: "3458.0000000001", ts: T0 + 45n },
];

/** "3456.789012" -> 3456789012 * 10^12, the circuit's 1e18-scaled decimal. */
function scaled(decimal) {
  const [int, frac] = decimal.split(".");
  return BigInt(int) * 10n ** 18n + BigInt(frac) * 10n ** BigInt(18 - frac.length);
}

async function prove(input) {
  const expected = [input.providerId, input.queryCommitment, input.price, input.observedAt, input.bodyCommitment];
  const { proof, publicSignals } = await snarkjs.groth16.fullProve(stringify(input), WASM, ZKEY);
  if (!(await snarkjs.groth16.verify(vkey, publicSignals, proof))) throw new Error("local verification failed");
  if (publicSignals.length !== expected.length || publicSignals.some((s, i) => BigInt(s) !== BigInt(expected[i])))
    throw new Error(`public signal order mismatch:\n got ${publicSignals}\n exp ${expected}`);
  const [a, b, c] = JSON.parse(`[${await snarkjs.groth16.exportSolidityCallData(proof, publicSignals)}]`);
  const words = [...a, ...b[0], ...b[1], ...c].map((x) => BigInt(x).toString(16).padStart(64, "0"));
  return "0x" + words.join(""); // == abi.encode(uint256[2], uint256[2][2], uint256[2])
}

const rows = [];
for (const { price, ts } of SERIES) {
  const text = `{"symbol":"${SYMBOL}","price":${price},"ts":${ts}}`;
  const body = [...Buffer.from(text, "latin1")];
  if (body.length > 96) throw new Error(`body longer than 96 bytes: ${text}`);
  while (body.length < 96) body.push(0);
  const [intPart, fracPart] = price.split(".");
  const input = {
    providerId,
    queryCommitment,
    price: scaled(price),
    observedAt: ts,
    bodyCommitment: h(...[0, 1, 2, 3].map((j) => pack(body.slice(j * 24, (j + 1) * 24)))),
    body,
    symbol,
    salt,
    offSymKey: text.indexOf('"symbol":"'),
    offPriceKey: text.indexOf('"price":'),
    offTsKey: text.indexOf('"ts":'),
    intLen: intPart.length,
    fracLen: fracPart.length,
  };
  rows.push({ text, input, snark: await prove(input) });
  console.log(`  proved ${text}`);
}

const entry = (r, i) => `        if (i == ${i}) {
            // ${r.text}
            return Attested({
                price: ${r.input.price},
                observedAt: ${r.input.observedAt},
                bodyCommitment: ${hex32(r.input.bodyCommitment)},
                snark: hex"${r.snark.slice(2)}"
            });
        }
`;

writeFileSync(
  OUT,
  `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;
// GENERATED by circuits/scripts/gen-feed-fixtures.mjs: real Groth16 proofs of circuits/zkdeco_oracle against the
// DEV verification key (test/fixtures/OracleGroth16Verifier.dev.sol), for an ETHUSD series 15 s apart.

library FeedFixtures {
    /// @dev keccak256("StrawberrySwap.testnet.price-endpoint") mod p: a test registry key.
    bytes32 internal constant PROVIDER_ID = ${hex32(providerId)};
    /// @dev Poseidon(pack("ETHUSD"), salt): the instrument, hidden behind its commitment.
    bytes32 internal constant ETHUSD_QUERY_COMMITMENT = ${hex32(queryCommitment)};
    uint256 internal constant COUNT = ${rows.length};

    struct Attested {
        uint256 price; // 1e18-scaled decimal, as attested
        uint64 observedAt;
        bytes32 bodyCommitment;
        bytes snark; // abi.encode(uint256[2] a, uint256[2][2] b, uint256[2] c)
    }

    function ethusd(uint256 i) internal pure returns (Attested memory) {
${rows.map(entry).join("")}        revert("FeedFixtures: no such attestation");
    }
}
`,
);
console.log(`wrote ${OUT}`);
// snarkjs keeps its worker threads alive after proving; exit explicitly so scripted pipelines do not hang.
process.exit(0);
