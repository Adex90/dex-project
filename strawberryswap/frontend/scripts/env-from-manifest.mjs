// The frontend's build configuration for a testnet deployment, from the manifest contracts/script/DeployTestnet.s.sol
// wrote (contracts/deployments/<chainId>.json). Every value is inlined into the public bundle at `next build`, so the
// site's IPFS CID commits to the exact chain and contracts it talks to.
//
//   node scripts/env-from-manifest.mjs ../contracts/deployments/421614.json [--rpc-url URL] [--automator-url URL] \
//        [--out .env.production.local]
//
// Only Arbitrum Sepolia (421614) and anvil (31337) manifests are accepted, and only with the dev-key verifiers
// flagged: a testnet build always shows the trusted-bootstrap banner. The RPC URL ships in the bundle: never pass a
// URL with an API key in it (the default is Arbitrum's public endpoint).
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export const CHAINS = {
  421614: { name: "Arbitrum Sepolia", rpc: "https://sepolia-rollup.arbitrum.io/rpc", explorer: "https://sepolia.arbiscan.io" },
  31337: { name: "Anvil", rpc: "http://127.0.0.1:8545", explorer: "" },
};

const ADDRESS = /^0x[0-9a-fA-F]{40}$/;
const SAFE_VALUE = /^[^\s"'`$\\#]*$/; // one dotenv token, nothing to expand or comment out

function address(manifest, key) {
  const value = manifest.contracts?.[key];
  if (typeof value !== "string" || !ADDRESS.test(value) || /^0x0{40}$/.test(value)) throw new Error(`manifest: contracts.${key} is not an address`);
  return value;
}

function url(value, flag, { httpsOnly }) {
  if (!SAFE_VALUE.test(value)) throw new Error(`${flag}: not a plain URL`);
  const u = new URL(value);
  if (u.protocol !== "https:" && (httpsOnly || u.protocol !== "http:")) throw new Error(`${flag}: must be https`);
  if (u.username || u.password) throw new Error(`${flag}: credentials would ship in the public bundle`);
  return value.replace(/\/$/, "");
}

/** The NEXT_PUBLIC_* variables for `manifest` (parsed JSON), as ordered [name, value] pairs. */
export function envFromManifest(manifest, { rpcUrl, automatorUrl } = {}) {
  const chainId = Number(manifest.chainId);
  const chain = CHAINS[chainId];
  if (!chain) throw new Error(`manifest: chain ${manifest.chainId} is not a testnet this script builds for (421614, 31337)`);
  if (manifest.devKeyVerifiers !== true) throw new Error("manifest: devKeyVerifiers must be true (a testnet deployment of DeployTestnet.s.sol)");
  const deployBlock = Number(manifest.deployBlock);
  if (!Number.isSafeInteger(deployBlock) || deployBlock < 0) throw new Error("manifest: deployBlock is not a block number");
  const live = chainId !== 31337;
  return [
    ["NEXT_PUBLIC_CHAIN_ID", String(chainId)],
    ["NEXT_PUBLIC_CHAIN_NAME", chain.name],
    ["NEXT_PUBLIC_RPC_URL", url(rpcUrl ?? chain.rpc, "--rpc-url", { httpsOnly: live })],
    ["NEXT_PUBLIC_DARKPOOL_ADDRESS", address(manifest, "pool")],
    ["NEXT_PUBLIC_VAULT_ADDRESS", ""],
    ["NEXT_PUBLIC_AUTOMATOR_URL", automatorUrl ? url(automatorUrl, "--automator-url", { httpsOnly: false }) : ""],
    ["NEXT_PUBLIC_DEPLOY_BLOCK", String(deployBlock)],
    ["NEXT_PUBLIC_LOG_CHUNK", "2000"],
    ["NEXT_PUBLIC_TESTNET", "1"],
    ["NEXT_PUBLIC_EXPLORER_URL", chain.explorer],
    ["NEXT_PUBLIC_DISCLOSURE_ADDRESS", address(manifest, "disclosure")],
    ["NEXT_PUBLIC_TWETH_ADDRESS", address(manifest, "tWETH")],
    ["NEXT_PUBLIC_TUSD_ADDRESS", address(manifest, "tUSD")],
  ];
}

export function render(pairs, source) {
  return [`# Generated by scripts/env-from-manifest.mjs from ${source}. Do not edit: regenerate.`, ...pairs.map(([k, v]) => `${k}=${v}`)].join("\n") + "\n";
}

function main(argv) {
  const args = [...argv];
  const flags = {};
  const positional = [];
  while (args.length) {
    const a = args.shift();
    if (a === "--rpc-url" || a === "--automator-url" || a === "--out") {
      if (!args.length) throw new Error(`${a} needs a value`);
      flags[a] = args.shift();
    } else if (a.startsWith("--")) throw new Error(`unknown flag ${a}`);
    else positional.push(a);
  }
  if (positional.length !== 1) throw new Error("usage: env-from-manifest.mjs <deployments/<chainId>.json> [--rpc-url URL] [--automator-url URL] [--out FILE]");
  const manifest = JSON.parse(readFileSync(positional[0], "utf8"));
  const text = render(envFromManifest(manifest, { rpcUrl: flags["--rpc-url"], automatorUrl: flags["--automator-url"] }), positional[0]);
  if (flags["--out"]) {
    writeFileSync(flags["--out"], text, { mode: 0o644 });
    console.error(`env-from-manifest: wrote ${flags["--out"]} (chain ${manifest.chainId}, pool ${manifest.contracts.pool})`);
  } else process.stdout.write(text);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  try {
    main(process.argv.slice(2));
  } catch (e) {
    console.error(`env-from-manifest: ${e.message}`);
    process.exit(1);
  }
}
