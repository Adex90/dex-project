// node --test scripts/env-from-manifest.test.mjs
import assert from "node:assert/strict";
import { test } from "node:test";
import { envFromManifest, render } from "./env-from-manifest.mjs";

const manifest = () => ({
  network: "arbitrum-sepolia",
  chainId: 421614,
  deployBlock: 123456789,
  devKeyVerifiers: true,
  batchSize: 4,
  contracts: {
    pool: "0x1111111111111111111111111111111111111111",
    disclosure: "0x2222222222222222222222222222222222222222",
    tWETH: "0x3333333333333333333333333333333333333333",
    tUSD: "0x4444444444444444444444444444444444444444",
  },
});

test("an Arbitrum Sepolia manifest makes a testnet build on the public RPC", () => {
  const env = Object.fromEntries(envFromManifest(manifest()));
  assert.equal(env.NEXT_PUBLIC_CHAIN_ID, "421614");
  assert.equal(env.NEXT_PUBLIC_CHAIN_NAME, "Arbitrum Sepolia");
  assert.equal(env.NEXT_PUBLIC_RPC_URL, "https://sepolia-rollup.arbitrum.io/rpc");
  assert.equal(env.NEXT_PUBLIC_DARKPOOL_ADDRESS, "0x1111111111111111111111111111111111111111");
  assert.equal(env.NEXT_PUBLIC_DEPLOY_BLOCK, "123456789");
  assert.equal(env.NEXT_PUBLIC_TESTNET, "1");
  assert.equal(env.NEXT_PUBLIC_EXPLORER_URL, "https://sepolia.arbiscan.io");
  assert.equal(env.NEXT_PUBLIC_DISCLOSURE_ADDRESS, "0x2222222222222222222222222222222222222222");
  assert.equal(env.NEXT_PUBLIC_TWETH_ADDRESS, "0x3333333333333333333333333333333333333333");
  assert.equal(env.NEXT_PUBLIC_TUSD_ADDRESS, "0x4444444444444444444444444444444444444444");
  const text = render(envFromManifest(manifest()), "deployments/421614.json");
  assert.match(text, /^# Generated by scripts\/env-from-manifest\.mjs/);
  assert.match(text, /\nNEXT_PUBLIC_CHAIN_NAME=Arbitrum Sepolia\n/);
});

test("never a build for another chain, or without the dev-key flag", () => {
  assert.throws(() => envFromManifest({ ...manifest(), chainId: 42161 }), /not a testnet/);
  assert.throws(() => envFromManifest({ ...manifest(), chainId: 1 }), /not a testnet/);
  assert.throws(() => envFromManifest({ ...manifest(), devKeyVerifiers: false }), /devKeyVerifiers/);
});

test("the RPC URL ships in the bundle: https, no credentials, nothing to expand", () => {
  assert.throws(() => envFromManifest(manifest(), { rpcUrl: "http://node.example/rpc" }), /https/);
  assert.throws(() => envFromManifest(manifest(), { rpcUrl: "https://user:secret@node.example/rpc" }), /credentials/);
  assert.throws(() => envFromManifest(manifest(), { rpcUrl: "https://node.example/rpc#x" }), /plain URL/);
  assert.throws(() => envFromManifest(manifest(), { rpcUrl: "https://node.example/$KEY" }), /plain URL/);
  const env = Object.fromEntries(envFromManifest(manifest(), { rpcUrl: "https://rpc.example/arb-sepolia/" }));
  assert.equal(env.NEXT_PUBLIC_RPC_URL, "https://rpc.example/arb-sepolia");
});

test("addresses and the deploy block are checked", () => {
  const m = manifest();
  m.contracts.pool = "0x0000000000000000000000000000000000000000";
  assert.throws(() => envFromManifest(m), /contracts\.pool/);
  const n = manifest();
  delete n.contracts.disclosure;
  assert.throws(() => envFromManifest(n), /contracts\.disclosure/);
  assert.throws(() => envFromManifest({ ...manifest(), deployBlock: -1 }), /deployBlock/);
});

test("an anvil manifest builds against the local node, without an explorer", () => {
  const env = Object.fromEntries(envFromManifest({ ...manifest(), chainId: 31337 }));
  assert.equal(env.NEXT_PUBLIC_RPC_URL, "http://127.0.0.1:8545");
  assert.equal(env.NEXT_PUBLIC_EXPLORER_URL, "");
  assert.equal(env.NEXT_PUBLIC_TESTNET, "1");
});
